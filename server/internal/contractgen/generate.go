// Package contractgen keeps HTTP schemas and clients tied to Go wire definitions.
// Unsupported types produce generation errors rather than runtime panics.
package contractgen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"reflect"
	"sort"
	"strings"

	"github.com/tomanagle/harness-kit/server/internal/wire"
)

// Generate writes or checks artifacts beneath the repository containing start.
func Generate(start string, check bool) error {
	root := start
	var err error

	for {
		if _, err := os.Stat(filepath.Join(root, "server/internal/wire/types.go")); err == nil {
			break
		}
		parent := filepath.Dir(root)
		if parent == root {
			return fmt.Errorf("repository root not found")
		}
		root = parent
	}
	types := map[string]reflect.Type{}
	var visit func(reflect.Type)
	visit = func(t reflect.Type) {
		if t == reflect.TypeFor[json.RawMessage]() {
			return
		}
		if t.Kind() == reflect.Slice || t.Kind() == reflect.Map {
			visit(t.Elem())
			return
		}
		if t.Kind() != reflect.Struct {
			return
		}
		if _, ok := types[t.Name()]; ok {
			return
		}
		types[t.Name()] = t
		for i := 0; i < t.NumField(); i++ {
			visit(t.Field(i).Type)
		}
	}
	visit(reflect.TypeFor[wire.Error]())
	for _, m := range wire.Methods {
		visit(m.Input)
		visit(m.Output)
	}
	names := make([]string, 0, len(types))
	for n := range types {
		names = append(names, n)
	}
	sort.Strings(names)
	var ts strings.Builder
	ts.WriteString("// Code generated by server/cmd/contractgen. DO NOT EDIT.\nimport type { RemoteTransport, RemoteRequestOptions } from './remote.ts';\n")
	defs := map[string]any{}
	for _, name := range names {
		t := types[name]
		fmt.Fprintf(&ts, "export interface %s {\n", name)
		props := map[string]any{}
		required := []string{}
		for i := 0; i < t.NumField(); i++ {
			f := t.Field(i)
			key := strings.Split(f.Tag.Get("json"), ",")[0]
			typ, err := tsType(f.Type)
			if err != nil {
				return fmt.Errorf("%s.%s: %w", name, f.Name, err)
			}
			shape, err := schema(f.Type)
			if err != nil {
				return fmt.Errorf("%s.%s: %w", name, f.Name, err)
			}
			optional := strings.Contains(f.Tag.Get("json"), ",omitempty")
			suffix := ""
			if optional {
				suffix = "?"
			}
			fmt.Fprintf(&ts, "  %s%s: %s;\n", key, suffix, typ)
			props[key] = shape
			if !optional {
				required = append(required, key)
			}
		}
		ts.WriteString("}\n")
		defs[name] = map[string]any{"type": "object", "properties": props, "required": required, "additionalProperties": false}
	}
	ts.WriteString("export class RemoteProtocol {\n private readonly transport: RemoteTransport;\n constructor(transport: RemoteTransport) { this.transport = transport; }\n")
	methods := map[string]any{}
	var goMethods strings.Builder
	goMethods.WriteString("// Code generated by server/cmd/contractgen. DO NOT EDIT.\npackage remote\nimport \"context\"\n")
	for _, m := range wire.Methods {
		name := strings.ToLower(m.Name[:1]) + m.Name[1:]
		fmt.Fprintf(&ts, "%s(params: %s, options?: RemoteRequestOptions): Promise<%s> { return this.transport.request('/v1/%s', params, options); }\n", name, m.Input.Name(), m.Output.Name(), m.Path)
		fmt.Fprintf(&goMethods, "func(c *Client) %s(ctx context.Context,in %s)(%s,error){var out %s;err:=c.request(ctx,\"/v1/%s\",in,&out);return out,err}\n", m.Name, m.Input.Name(), m.Output.Name(), m.Output.Name(), m.Path)
		input, err := schema(m.Input)
		if err != nil {
			return fmt.Errorf("%s request: %w", m.Name, err)
		}
		output, err := schema(m.Output)
		if err != nil {
			return fmt.Errorf("%s response: %w", m.Name, err)
		}
		methods["/v1/"+m.Path] = map[string]any{"request": input, "response": output}
	}
	ts.WriteString("}\n")
	jsonBytes, err := json.MarshalIndent(map[string]any{"$schema": "https://json-schema.org/draft/2020-12/schema", "$id": "https://harness-kit.dev/protocol/server-v1.schema.json", "$defs": defs, "x-methods": methods}, "", "  ")
	if err != nil {
		return err
	}
	goTypes, err := os.ReadFile(filepath.Join(root, "server/internal/wire/types.go"))
	if err != nil {
		return err
	}
	offset := bytes.Index(goTypes, []byte("package wire"))
	if offset < 0 {
		return fmt.Errorf("wire types package declaration not found")
	}
	goTypes = append([]byte("// Code generated by server/cmd/contractgen. DO NOT EDIT.\n"), bytes.Replace(goTypes[offset:], []byte("package wire"), []byte("package remote"), 1)...)
	outputs := map[string][]byte{"protocol/server-v1.schema.json": append(jsonBytes, '\n'), "packages/client-ts/src/remote.gen.ts": []byte(ts.String()), "packages/client-go/remote/types.gen.go": goTypes, "packages/client-go/remote/methods.gen.go": []byte(goMethods.String())}
	for path, b := range outputs {
		if strings.HasSuffix(path, ".go") {
			b, err = format.Source(b)
			if err != nil {
				return err
			}
		}
		path = filepath.Join(root, path)
		if check {
			existing, e := os.ReadFile(path)
			if e != nil || !bytes.Equal(existing, b) {
				return fmt.Errorf("generated file is stale: %s", path)
			}
		} else {
			if err = os.WriteFile(path, b, 0644); err != nil {
				return err
			}
		}
	}
	return nil
}
