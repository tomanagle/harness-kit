package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"slices"
	"strings"
)

const generated = "// Code generated by core/cmd/protocolgen from protocol/schema.json; DO NOT EDIT.\n// Regenerate with make generate.\n\n"

func render(d *Document) (map[string][]byte, error) {
	goTypes, err := renderGo(d)
	if err != nil {
		return nil, err
	}
	goMethods, err := renderGoMethods(d)
	if err != nil {
		return nil, err
	}
	return map[string][]byte{
		"packages/client-ts/src/protocol.ts":    renderTS(d),
		"packages/client-ts/src/methods.gen.ts": renderTSMethods(d),
		"packages/client-go/protocol.gen.go":    goTypes,
		"packages/client-go/methods.gen.go":     goMethods,
	}, nil
}

func encoded(value any) string {
	b, err := json.Marshal(value)
	if err != nil {
		panic(err)
	}
	return string(b)
}

func comment(out *bytes.Buffer, text, indent string) {
	for _, line := range strings.Split(strings.TrimSpace(text), "\n") {
		if line != "" {
			fmt.Fprintf(out, "%s// %s\n", indent, line)
		}
	}
}

func renderTS(d *Document) []byte {
	var out bytes.Buffer
	out.WriteString(generated)
	fmt.Fprintf(&out, "export const PROTOCOL_VERSION = %d;\n\nexport const ErrorCodes = {\n", d.Version)
	for _, name := range sortedKeys(d.Constants) {
		if strings.HasPrefix(name, "Code") {
			fmt.Fprintf(&out, "  %s: %s,\n", strings.TrimPrefix(name, "Code"), encoded(d.Constants[name]))
		}
	}
	out.WriteString("} as const;\n\n")
	for _, name := range sortedKeys(d.Defs) {
		s := d.Defs[name]
		comment(&out, s.Description, "")
		if name == "HarnessEvent" {
			out.WriteString("export type HarnessEvent =\n")
			for _, variant := range s.OneOf {
				// Keep the public TypeScript union discriminated. The wire schema
				// also permits unknown future events; consumers must ignore them.
				if variant.Properties["type"].Const != nil {
					fmt.Fprintf(&out, "  | %s\n", tsType(variant))
				}
			}
			out.WriteString(";\n\n")
			continue
		}
		if s.Type == "object" && s.AdditionalProperties == nil {
			fmt.Fprintf(&out, "export interface %s {\n", name)
			for _, field := range sortedKeys(s.Properties) {
				p := s.Properties[field]
				comment(&out, p.Description, "  ")
				optional := "?"
				if slices.Contains(s.Required, field) {
					optional = ""
				}
				fmt.Fprintf(&out, "  %s%s: %s;\n", field, optional, tsType(p))
			}
			out.WriteString("}\n\n")
		} else {
			fmt.Fprintf(&out, "export type %s = %s;\n\n", name, tsType(s))
		}
	}
	out.WriteString("export type EventData<T extends EventType> = Extract<HarnessEvent, { type: T }>[\"data\"];\n\n")
	out.WriteString("/** The complete generated client-to-server request contract. */\nexport interface RpcMethods {\n")
	for _, name := range sortedKeys(d.Methods) {
		m := d.Methods[name]
		p := "undefined"
		if m.Params != nil {
			p = tsType(m.Params)
		}
		fmt.Fprintf(&out, "  %s: { params: %s; result: %s };\n", encoded(name), p, tsType(m.Result))
	}
	out.WriteString("}\nexport type RpcMethod = keyof RpcMethods;\n\nexport interface ServerRequests {\n")
	for _, name := range sortedKeys(d.Requests) {
		m := d.Requests[name]
		fmt.Fprintf(&out, "  %s: { params: %s; result: %s };\n", encoded(name), tsType(m.Params), tsType(m.Result))
	}
	out.WriteString("}\n\nexport interface Notifications {\n")
	for _, name := range sortedKeys(d.Notifications) {
		fmt.Fprintf(&out, "  %s: %s;\n", encoded(name), tsType(d.Notifications[name]))
	}
	out.WriteString("}\n")
	return out.Bytes()
}

func tsType(s *Schema) string {
	if s.Ref != "" {
		return refName(s)
	}
	if s.Const != nil {
		return encoded(s.Const)
	}
	if len(s.Enum) > 0 {
		v := make([]string, len(s.Enum))
		for i, x := range s.Enum {
			v[i] = encoded(x)
		}
		return strings.Join(v, " | ")
	}
	if len(s.AnyOf) > 0 {
		v := make([]string, len(s.AnyOf))
		for i, x := range s.AnyOf {
			v[i] = tsType(x)
		}
		return strings.Join(v, " | ")
	}
	switch s.Type {
	case "string":
		return "string"
	case "boolean":
		return "boolean"
	case "integer", "number":
		return "number"
	case "null":
		return "null"
	case "array":
		return "Array<" + tsType(s.Items) + ">"
	case "object":
		if s.AdditionalProperties != nil {
			return "Record<string, " + tsType(s.AdditionalProperties) + ">"
		}
		var fields []string
		for _, name := range sortedKeys(s.Properties) {
			optional := "?"
			if slices.Contains(s.Required, name) {
				optional = ""
			}
			fields = append(fields, encoded(name)+optional+": "+tsType(s.Properties[name]))
		}
		return "{ " + strings.Join(fields, "; ") + " }"
	default:
		return "unknown"
	}
}

func renderTSMethods(d *Document) []byte {
	var out bytes.Buffer
	out.WriteString(generated)
	out.WriteString("import type { RpcMethod, RpcMethods } from \"./protocol.ts\";\nimport type { RequestOptions } from \"./rpc.ts\";\n\n")
	out.WriteString("export type RpcRequester = <M extends RpcMethod>(method: M, params: RpcMethods[M][\"params\"], opts?: RequestOptions) => Promise<RpcMethods[M][\"result\"]>;\n\n")
	out.WriteString("/** Typed wire methods. Transport and higher-level session helpers are separate. */\nexport class ProtocolClient {\n  readonly #request: RpcRequester;\n  constructor(request: RpcRequester) { this.#request = request; }\n\n")
	for _, name := range sortedKeys(d.Methods) {
		m := d.Methods[name]
		lower := strings.ToLower(m.GoName[:1]) + m.GoName[1:]
		arg := ""
		param := "undefined"
		if m.Params != nil {
			arg = "params: RpcMethods[" + encoded(name) + "][\"params\"], "
			param = "params"
		}
		fmt.Fprintf(&out, "  %s(%sopts?: RequestOptions): Promise<RpcMethods[%s][\"result\"]> {\n    return this.#request(%s, %s, opts);\n  }\n\n", lower, arg, encoded(name), encoded(name), param)
	}
	out.WriteString("}\n")
	return out.Bytes()
}

func renderGo(d *Document) ([]byte, error) {
	var out bytes.Buffer
	out.WriteString(generated + "package harnesskit\n\nimport (\n\"encoding/json\"\n\"time\"\n)\n\n")
	fmt.Fprintf(&out, "const Version = %d\n\nconst (\n", d.Version)
	for _, name := range sortedKeys(d.Constants) {
		fmt.Fprintf(&out, "%s = %s\n", name, encoded(d.Constants[name]))
	}
	out.WriteString(")\n\n")
	for _, name := range sortedKeys(d.Defs) {
		s := d.Defs[name]
		comment(&out, s.Description, "")
		if s.Type == "object" && s.AdditionalProperties == nil && !strings.HasPrefix(s.GoType, "map[") {
			fmt.Fprintf(&out, "type %s struct {\n", name)
			for _, field := range sortedKeys(s.Properties) {
				p := s.Properties[field]
				if p.GoName == "" {
					return nil, fmt.Errorf("missing Go field name: %s.%s", name, field)
				}
				comment(&out, p.Description, "")
				tag := p.GoJSONTag
				if tag == "" {
					tag = field
				}
				fmt.Fprintf(&out, "%s %s `json:%s`\n", p.GoName, goType(p), encoded(tag))
			}
			out.WriteString("}\n\n")
		} else {
			fmt.Fprintf(&out, "type %s %s\n\n", name, goType(s))
		}
		if len(s.Enum) > 0 {
			out.WriteString("const (\n")
			for _, value := range s.Enum {
				fmt.Fprintf(&out, "%s%s %s = %s\n", name, enumName(value), name, encoded(value))
			}
			out.WriteString(")\n\n")
		}
	}
	return format.Source(out.Bytes())
}

func goType(s *Schema) string {
	if s.GoType != "" {
		return s.GoType
	}
	if s.Ref != "" {
		return refName(s)
	}
	panic("schema missing Go type")
}

func enumName(value string) string {
	parts := strings.FieldsFunc(value, func(r rune) bool { return r == '.' || r == '_' || r == '-' })
	for i, s := range parts {
		parts[i] = strings.ToUpper(s[:1]) + s[1:]
	}
	return strings.Join(parts, "")
}

func renderGoMethods(d *Document) ([]byte, error) {
	var out bytes.Buffer
	out.WriteString(generated + "package harnesskit\n\nimport \"context\"\n\n")
	for _, name := range sortedKeys(d.Methods) {
		m := d.Methods[name]
		param := "nil"
		arg := ""
		if m.Params != nil {
			param = "params"
			arg = ", params " + goType(m.Params)
		}
		fmt.Fprintf(&out, "// %s calls %s.\nfunc (c *Client) %s(ctx context.Context%s) (%s, error) {\nvar result %s\nerr := c.Call(ctx, %s, %s, &result)\nreturn result, err\n}\n\n", m.GoName, name, m.GoName, arg, goType(m.Result), goType(m.Result), encoded(name), param)
	}
	return format.Source(out.Bytes())
}
